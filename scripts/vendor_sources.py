def _fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=30) as resp:  # noqa: S310 - pinned https URLs only
        return resp.read()


# --- Linguist: minimal, purpose-built languages.yml reader --------------
# Not a general YAML parser. It relies on the file's stable, documented
# structure (top-level "Language Name:" keys, 2-space indented scalar
# fields, "  extensions:"/"  filenames:" followed by "  - value" list
# items) which the Linguist maintainers describe explicitly in the file's
# own header comment. Anything else in the file is ignored.

_LANG_HEADER = re.compile(r"^(\S.*):\s*$")
_FIELD_HEADER = re.compile(r"^  (\w+):\s*$")
_LIST_ITEM = re.compile(r'^  - (?:"([^"]*)"|(\S+))\s*$')


def _parse_languages_yml(text: str) -> dict[str, dict[str, list[str]]]:
    languages: dict[str, dict[str, list[str]]] = {}
    current_lang: str | None = None
    current_field: str | None = None

    for raw_line in text.splitlines():
        if not raw_line.strip() or raw_line.lstrip().startswith("#"):
            continue
        if not raw_line.startswith(" "):
            match = _LANG_HEADER.match(raw_line)
            if match:
                current_lang = match.group(1)
                languages[current_lang] = {"extensions": [], "filenames": []}
                current_field = None
            continue
        field_match = _FIELD_HEADER.match(raw_line)
        if field_match:
            current_field = field_match.group(1)
            continue
        item_match = _LIST_ITEM.match(raw_line)
        if item_match and current_lang and current_field in ("extensions", "filenames"):
            quoted, bare = item_match.group(1), item_match.group(2)
            value = quoted if quoted is not None else bare
            languages[current_lang][current_field].append(value)

    return {
        name: fields
        for name, fields in languages.items()
        if fields["extensions"] or fields["filenames"]
    }


def fetch_linguist() -> dict:
    raw = _fetch(LINGUIST_URL)
    languages = _parse_languages_yml(raw.decode("utf-8"))
    _validate_linguist(languages)
    return {
        "meta": {
            "source_url": LINGUIST_URL,
            "pinned_commit": LINGUIST_COMMIT,
            "retrieved": _retrieved_now(),
            "license": LINGUIST_LICENSE,
            "attribution": LINGUIST_ATTRIBUTION,
        },
        "languages": languages,
    }


# --- Linguist vendor.yml: third-party categories only (T087) -------------

_VENDOR_SECTION = re.compile(r"^##\s*(.*?)\s*##\s*$")
_VENDOR_CATEGORY = re.compile(r"^#(?!#)\s*(.*?)\s*$")
_VENDOR_PATTERN = re.compile(r"^- (.+?)\s*$")


def _parse_vendor_yml(text: str) -> list[tuple[str, list[str]]]:
    """``[(section / category, [regex, ...]), ...]`` in file order. Relies on
    the file's documented shape: ``## Section ##`` and ``# Category`` comment
    lines above ``- regex`` list items. Not a general YAML parser."""
    section = "Vendor Conventions"
    category: str | None = None
    out: list[tuple[str, list[str]]] = []
    for line in text.splitlines():
        if match := _VENDOR_SECTION.match(line):
            section, category = match.group(1), None
        elif line.startswith("###"):
            continue
        elif (match := _VENDOR_CATEGORY.match(line)) and match.group(1):
            category = f"{section} / {match.group(1)}"
        elif match := _VENDOR_PATTERN.match(line):
            if category is None:
                raise UpstreamFormatError(
                    f"vendor.yml: pattern before any category: {line!r}"
                )
            if not out or out[-1][0] != category:
                out.append((category, []))
            out[-1][1].append(match.group(1))
    return out


def _filter_vendor(categories: list[tuple[str, list[str]]]) -> dict:
    if len(categories) < 80:
        raise UpstreamFormatError(
            f"vendor.yml: expected >= 80 categories, parsed only {len(categories)}"
        )
    unknown = [name for name, _ in categories if name not in VENDOR_CATEGORIES]
    if unknown:
        raise UpstreamFormatError(f"vendor.yml: unclassified categories {unknown}")
    kept: list[dict] = []
    dropped: list[dict] = []
    for name, patterns in categories:
        keep, reason = VENDOR_CATEGORIES[name]
        for pattern in patterns:
            re.compile(pattern)  # every regex must be valid Python syntax too
        if not keep:
            dropped.append({"category": name, "patterns": patterns, "reason": reason})
            continue
        drops = [p for p in patterns if p in VENDOR_PATTERN_DROPS]
        for pattern in drops:
            dropped.append(
                {
                    "category": name,
                    "patterns": [pattern],
                    "reason": VENDOR_PATTERN_DROPS[pattern],
                }
            )
        kept.append(
            {
                "category": name,
                "patterns": [p for p in patterns if p not in drops],
                "reason": reason,
            }
        )
    names = {p for item in kept for p in item["patterns"]}
    for required in ("(^|/)node_modules/", "(^|/)vendors?/", "(\\.|-)min\\.(js|css)$"):
        if required not in names:
            raise UpstreamFormatError(
                f"vendor.yml: expected kept pattern {required!r} missing"
            )
    return {"kept": kept, "dropped": dropped}


