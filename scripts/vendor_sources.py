def _vendor_category_lines() -> str:
    path = VENDORED_DIR / "linguist_vendor.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    lines = [
        f"  kept    {item['category']} -- {item['reason']}" for item in data["kept"]
    ] + [
        f"  dropped {item['category']}"
        + (
            f" {item['patterns'][0]}"
            if item["category"] in {k["category"] for k in data["kept"]}
            else ""
        )
        + f" -- {item['reason']}"
        for item in data["dropped"]
    ]
    return "\n".join(lines)


